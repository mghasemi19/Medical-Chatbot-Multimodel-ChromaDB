"""Ingest a PDF into the project's persistent local ChromaDB collection."""

import argparse
import hashlib
from pathlib import Path

import fitz  # PyMuPDF — extracts selectable text from PDF pages.

# Reuse the app's embedding and persistent ChromaDB helpers so ingestion and
# chat write to and search the same local collection.
from app.knowledge import embed, get_collection, upsert_chunks


def chunks(text, size=1100, overlap=180):
    """Split page text into overlapping chunks and skip tiny fragments."""
    # Collapse line breaks and repeated whitespace before chunking the PDF text.
    text = " ".join(text.split())
    # Advance by less than the chunk size so adjacent chunks share context.
    step = size - overlap
    return [
        text[i:i + size]
        for i in range(0, len(text), step)
        if len(text[i:i + size]) > 80
    ]


def main():
    # Allow the PDF path to be overridden from the command line.
    parser = argparse.ArgumentParser(description="Ingest a PDF into local ChromaDB.")
    parser.add_argument(
        "--pdf",
        default="data/Medical_book.pdf",
        help="Path to the source PDF (default: data/Medical_book.pdf)",
    )
    args = parser.parse_args()

    pdf = Path(args.pdf)
    # Fail early with a clear message instead of starting a costly embedding run.
    if not pdf.exists():
        raise SystemExit(f"PDF not found: {pdf}")

    # Open the configured local collection and remember existing records for this PDF.
    collection = get_collection()
    
    # Keep old IDs for this PDF so stale trailing chunks can be removed after a
    # successful re-ingestion; an interrupted ingestion won't erase old records.
    previous = collection.get(where={"file": pdf.name}, include=["metadatas"])
    previous_ids = set(previous.get("ids", []))
    # Track the IDs generated by this run to identify obsolete chunks after success.
    current_ids = set()

    # Extract text one page at a time to avoid loading the entire PDF's text at once.
    with fitz.open(pdf) as document:
        # Buffer chunks so embeddings and Chroma writes happen in manageable batches.
        batch = []
        for page_number, page in enumerate(document, start=1):
            for part_number, content in enumerate(chunks(page.get_text()), start=1):
                # Stable per-page/per-part IDs make repeat ingestion an update, not duplication.
                record_id = hashlib.sha256(
                    f"{pdf.name}:{page_number}:{part_number}".encode("utf-8")
                ).hexdigest()
                current_ids.add(record_id)
                metadata = {"page": page_number, "file": pdf.name}
                batch.append((record_id, content, metadata))

                # Embed and upsert each group of 50 chunks to limit API request size.
                if len(batch) >= 50:
                    vectors = embed([record[1] for record in batch])
                    upsert_chunks(
                        [(*record, vector) for record, vector in zip(batch, vectors)]
                    )
                    batch = []

            if page_number % 50 == 0:
                print(f"Processed pages: {page_number}/{len(document)}", flush=True)

        if batch:
            # Flush the final partial batch after the page loop finishes.
            vectors = embed([record[1] for record in batch])
            upsert_chunks([(*record, vector) for record, vector in zip(batch, vectors)])

    # Remove chunks left over from an older, longer version of this PDF.
    # Cleanup happens only after all current chunks were embedded and stored.
    stale_ids = previous_ids - current_ids
    if stale_ids:
        stale_ids = list(stale_ids)
        # Delete in smaller requests for large collections.
        for offset in range(0, len(stale_ids), 500):
            collection.delete(ids=stale_ids[offset:offset + 500])

    # Report the final collection size as a quick ingestion confirmation.
    print(f"Ingestion complete. Chroma collection now contains {collection.count()} chunks.")


# Run ingestion only when this script is executed directly, not when imported.
if __name__ == "__main__":
    main()
